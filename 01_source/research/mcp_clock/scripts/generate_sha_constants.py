"""Generate standard SHA-2 constants from prime roots (FIPS 180-4)."""
from decimal import Decimal, localcontext
from pathlib import Path

primes=[]
n=2
while len(primes)<80:
    if all(n%p for p in primes if p*p<=n): primes.append(n)
    n+=1
with localcontext() as ctx:
    ctx.prec=160
    def words(bits, degree, count):
        result=[]
        for p in primes[:count]:
            root=Decimal(p)**(Decimal(1)/degree)
            result.append(int((root-int(root))*(Decimal(2)**bits)))
        return result
    values=[('k256',32,words(32,3,64)),('iv256',32,words(32,2,8)),
            ('k512',64,words(64,3,80)),('iv512',64,words(64,2,8))]
lines=['// Standard SHA-2 constants; generated by scripts/generate_sha_constants.py.']
for name,bits,data in values:
    lines.append(f'constexpr std::uint{bits}_t {name}[] = {{')
    for i in range(0,len(data),4):
        lines.append('    '+', '.join(f'0x{x:0{bits//4}x}'+('ULL' if bits==64 else 'U') for x in data[i:i+4])+',')
    lines.append('};')
path=Path(__file__).resolve().parents[1]/'src/sha_constants.inc'
path.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(path)
